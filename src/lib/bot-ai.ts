/**
 * Семантические теги для осознанного выбора карт ботами.
 * Каждая ситуация и каждый мем размечены смысловыми тегами и ключевыми ассоциациями,
 * чтобы боты понимали контекст шутки, а не просто сравнивали название категории.
 */
export type SemanticTag =
  | "fail" // провал, ошибка, фиаско, проблемы
  | "cringe" // стыд, неловкость, хочется исчезнуть
  | "panic" // стресс, дедлайн, аврал, шок, пожар
  | "sleep" // сон, усталость, утро, кровать, лень, понедельник
  | "work" // офис, работа, код, прод, митинг, начальство
  | "escape" // побег, уход, невидимость, спрятаться, отмазка
  | "anger" // злость, раздражение, предательство, месть
  | "chill" // спокойствие, пофигизм, диван, кофе, расслабон
  | "food" // еда, холодильник, пицца, перекус, голод
  | "tech" // интернет, гаджеты, роботы, код, соцсети, звонки
  | "secret" // тайна, слежка, заговор, молчание
  | "flex" // успех, гордость, крутость, праздник, деньги, гений
  | "absurd" // сюр, безумие, космос, странная выходка, шоу
  | "animal" // коты, собаки, живность
  | "relatives" // мама, бабушка, семья
  | "waiting" // ожидание, медлительность, опоздание
  | "drama"; // драма, слёзы, эмоции на грани

type MemeProfile = {
  tags: SemanticTag[];
  /** Насколько мем универсален как живая реакция (0..10). */
  versatility: number;
  /** Ключевые слова/триггеры ситуаций, где этот мем бьёт точно в цель. */
  triggers?: string[];
};

type SituationProfile = {
  /** Главные смысловые теги (вес x3). */
  primary: SemanticTag[];
  /** Дополнительные подходящие теги (вес x1.5). */
  secondary: SemanticTag[];
  /** Тексты мемов, которые идеально подходят к этой ситуации (снайперское попадание). */
  bullseye: string[];
};


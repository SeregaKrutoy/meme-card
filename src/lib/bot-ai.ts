/**
 * Характер каждого бота: слегка влияет на его чувство юмора при прочих равных,
 * но никогда не перевешивает здравый смысл.
 */
const BOT_PERSONA_TAGS: Record<string, SemanticTag[]> = {
  "Кот-менеджер": ["work", "animal", "chill", "flex"],
  "Тётя Wi-Fi": ["tech", "relatives", "secret", "drama"],
  "Дедлайн": ["panic", "work", "fail", "sleep"],
  "Тимлид 3000": ["work", "tech", "anger", "panic"],
  "Бабушка-стример": ["relatives", "tech", "absurd", "flex"],
  "Курьер на месте": ["waiting", "food", "escape", "flex"],
  "Дед из подъезда": ["anger", "sleep", "secret", "absurd"],
};

/**
 * Размечает пользовательский мем по его тексту. Базовые карты используют
 * точную ручную разметку выше, а добавленные игроками всё равно становятся
 * понятны ботам по словам «дедлайн», «пицца», «стыд», «интернет» и т. п.
 */
function inferMemeProfile(card: CardView): MemeProfile {
  const exact = MEME_PROFILES[card.text];
  if (exact) return exact;

  const lower = card.text.toLowerCase();
  const tags: SemanticTag[] = [];
  const add = (...next: SemanticTag[]) => {
    for (const tag of next) if (!tags.includes(tag)) tags.push(tag);
  };

  if (/работ|офис|босс|тимлид|митинг|созвон|прод|дедлайн|код|коллег/.test(lower)) add("work");
  if (/интернет|робот|пароль|телефон|камер|сайт|бот|wi-?fi|комп/.test(lower)) add("tech");
  if (/сон|спат|кровать|утр|ноч|пятниц|понедельник|устал/.test(lower)) add("sleep");
  if (/пицц|ед[ау]|холодильник|кофе|чай|голод/.test(lower)) add("food", "chill");
  if (/стыд|кринж|неловк|позор|не тому|ошиб/.test(lower)) add("cringe", "fail");
  if (/паник|пожар|провал|фиаско|проблем|дедлайн|аврал/.test(lower)) add("panic", "fail");
  if (/сбеж|уйти|исчез|невидим|отпуск|прят/.test(lower)) add("escape");
  if (/зл|бесит|ярост|ненавиж|сверл|мест/.test(lower)) add("anger");
  if (/секрет|тайн|никому|шпион|след/.test(lower)) add("secret");
  if (/кот|собак|лягуш|живот|пингвин/.test(lower)) add("animal");
  if (/мама|папа|бабуш|дедуш|семь/.test(lower)) add("relatives");
  if (/побед|крут|идеаль|гени|деньг|успех/.test(lower)) add("flex");
  if (/космос|динозавр|единорог|маг|цирк|абсурд|мем/.test(lower)) add("absurd");
  if (/жду|потом|опозд|медлен|очеред/.test(lower)) add("waiting");

  if (tags.length === 0) add("absurd", "chill");
  return { tags, versatility: Math.min(8, 4 + tags.length), triggers: [card.text] };
}

/**
 * Вычисляет теги ситуации даже если текст немного отличается.
 */
function inferSituationProfile(situation: CardView): SituationProfile {
  const exact = SITUATION_PROFILES[situation.text];
  if (exact) return exact;

  const lower = situation.text.toLowerCase();
  const primary: SemanticTag[] = [];
  const secondary: SemanticTag[] = [];

  if (/работ|прод|митинг|созвон|тимлид|коллег|совещан|резюме|дедлайн|кофе/.test(lower)) {
    primary.push("work");
  }
  if (/интернет|робот|пароль|аккаунт|камер|авто|уведомлен|код|мем|тикток|лайк/.test(lower)) {
    primary.push("tech");
  }
  if (/утр|ноч|понедельник|сп|кроват|глаза/.test(lower)) {
    primary.push("sleep");
  }
  if (/ед[ау]|холодильник|горчиц|чайник/.test(lower)) {
    primary.push("food");
  }
  if (/не тому|стыд|смотрят|дорогая|чуж/.test(lower)) {
    primary.push("cringe");
  }
  if (/бед|пожар|застрял|унёс|без зонта|отключ/.test(lower)) {
    primary.push("fail", "panic");
  }
  if (/сбежат|невидим|опоздан/.test(lower)) {
    primary.push("escape");
  }
  if (/сверлит|без тебя|не скажу/.test(lower)) {
    primary.push("anger", "secret");
  }
  if (/кот|собак/.test(lower)) {
    primary.push("animal");
  }
  if (/мама|бабушк/.test(lower)) {
    primary.push("relatives");
  }

  if (primary.length === 0) {
    primary.push("cringe", "absurd", "fail");
  }
  secondary.push("drama", "chill", "flex");

  return { primary, secondary, bullseye: [] };
}

/**
 * Оценивает, насколько конкретная карта-мем подходит к ситуации (0..100+).
 * Чем выше балл, тем осознаннее и смешнее попадание.
 */
export function scoreMemeForSituation(
  card: CardView,
  situation: CardView | null,
  botName?: string,
): number {
  if (!situation) return 50;

  const sProfile = inferSituationProfile(situation);
  const mProfile = inferMemeProfile(card);

  let score = 0;

  // 1. Снайперское попадание из списка идеальных ответов к этой ситуации
  const bullseyeIdx = sProfile.bullseye.indexOf(card.text);
  if (bullseyeIdx !== -1) {
    score += 55 - bullseyeIdx * 3;
  }

  // 2. Прямое срабатывание ключевых слов ситуации в триггерах карты
  const sitLower = situation.text.toLowerCase();
  if (mProfile.triggers) {
    for (const trigger of mProfile.triggers) {
      if (sitLower.includes(trigger.toLowerCase())) {
        score += 32;
        break;
      }
    }
  }

  // 3. Пересечение главных и вторичных смысловых тегов
  for (const tag of mProfile.tags) {
    if (sProfile.primary.includes(tag)) {
      score += 22;
    } else if (sProfile.secondary.includes(tag)) {
      score += 10;
    }
  }

  // 4. Совпадение категории даёт небольшой бонус, но только если есть хоть какая-то связь
  if (card.category === situation.category) {
    score += 12;
  } else if (card.category === "реакция") {
    // Живые реакции отлично подходят почти к любой жизненной ситуации
    score += 8;
  }

  // 5. Универсальность и «панчевость» самого мема
  score += mProfile.versatility * 1.8;

  // 6. Лёгкий почерк конкретного бота (чтобы разные боты имели свой стиль при близких картах)
  if (botName && BOT_PERSONA_TAGS[botName]) {
    const persona = BOT_PERSONA_TAGS[botName];
    for (const tag of mProfile.tags) {
      if (persona.includes(tag)) {
        score += 4;
      }
    }
  }

  return score;
}

/**
 * Выбирает лучшую карту из руки бота для текущей ситуации.
 */
export function pickBestCardForBot(
  hand: CardView[],
  situation: CardView | null,
  botName?: string,
): CardView {
  if (hand.length === 0) {
    throw new Error("Hand is empty");
  }
  if (hand.length === 1 || !situation) {
    return hand[0];
  }

  const ranked = hand
    .map((card) => ({
      card,
      score: scoreMemeForSituation(card, situation, botName),
    }))
    .sort((a, b) => b.score - a.score);

  const best = ranked[0];
  const second = ranked[1];

  // Если две лучшие карты практически равны по смыслу (разница < 5 баллов),
  // допускаем выбор между ними для живого разнообразия; слабые карты никогда не берутся.
  if (second && best.score - second.score < 5 && Math.random() < 0.3) {
    return second.card;
  }
  return best.card;
}

/**
 * Выбирает лучший сыгранный ход глазами бота-судьи.
 */
export function pickBestPlayForBotJudge<T extends { card: CardView }>(
  plays: T[],
  situation: CardView | null,
  judgeName?: string,
): T {
  if (plays.length === 0) {
    throw new Error("No plays to judge");
  }
  if (plays.length === 1 || !situation) {
    return plays[0];
  }

  const ranked = plays
    .map((entry) => ({
      entry,
      score: scoreMemeForSituation(entry.card, situation, judgeName),
    }))
    .sort((a, b) => b.score - a.score);

  const best = ranked[0];
  const second = ranked[1];

  if (second && best.score - second.score < 4 && Math.random() < 0.25) {
    return second.entry;
  }
  return best.entry;
}

/**
 * Возвращает короткий осмысленный комментарий от судьи-бота, почему он выбрал этот мем.
 */
export function explainBotChoice(
  card: CardView,
  situation: CardView | null,
): string {
  if (!situation) return "Точное попадание в настроение раунда!";

  const sProfile = inferSituationProfile(situation);
  const mProfile = inferMemeProfile(card);

  if (sProfile.bullseye.includes(card.text)) {
    return "Снайперское попадание в самую суть ситуации!";
  }

  const shared = mProfile?.tags.filter((t) => sProfile.primary.includes(t)) ?? [];
  if (shared.includes("work") || shared.includes("panic")) {
    return "Жизненная рабочая боль передана на 10 из 10.";
  }
  if (shared.includes("cringe") || shared.includes("escape")) {
    return "Идеально передаёт желание провалиться сквозь землю.";
  }
  if (shared.includes("sleep") || shared.includes("waiting")) {
    return "Лучшее описание этого состояния.";
  }
  if (shared.includes("anger") || shared.includes("secret")) {
    return "Скрытая эмоция считана безошибочно!";
  }
  if (shared.includes("food") || shared.includes("chill")) {
    return "Максимально честная бытовая реакция.";
  }
  if (shared.includes("tech")) {
    return "Технологический юмор попал прямо в яблочко.";
  }
  return "Самая точная и смешная реакция из всех карт на столе!";
}
